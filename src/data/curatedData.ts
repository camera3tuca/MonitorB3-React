export function ehBdr(ticker: string): boolean {
  const t = String(ticker || '').trim().toUpperCase();
  const suf2 = t.slice(-2);
  return ['31', '32', '33', '34', '35', '39'].includes(suf2);
}

export function ehEtf(ticker: string): boolean {
  const t = String(ticker || '').trim().toUpperCase();
  return t.endsWith('39') || ETFS_B3.has(t);
}

export function mapearTickerUs(ticker: string): string {
  const t = String(ticker || '').trim().toUpperCase();
  if (BDR_TO_US_MAP[t]) return BDR_TO_US_MAP[t];
  if (ETF_US_MAP[t]) return ETF_US_MAP[t];
  // Remove numbers from end
  const stripped = t.replace(/\d+$/, '');
  return stripped || ticker;
}
